    public function run(): void
    {
        foreach ($this->materials() as $material) {
            $cover = $material['cover'];
            unset($material['cover']);

            $post = Post::query()->firstOrCreate(
                ['slug' => $material['slug']],
                $material + ['cover_path' => $this->storeCover($cover)],
            );

            // Обложка могла появиться позже самого материала.
            if ($post->cover_path === null) {
                $post->update(['cover_path' => $this->storeCover($cover)]);
            }
        }
    }

    /**
     * Кладёт файл обложки в хранилище и возвращает путь для модели.
     * Файлы лежат рядом с сеялкой, чтобы раздел собирался с картинками
     * на любом сервере, а не только там, где их загрузили руками.
     */
    private function storeCover(string $file): ?string
    {
        $source = __DIR__.'/covers/'.$file;
        if (! is_file($source)) {
            return null;
        }

        $path = 'posts/'.$file;
        if (! Storage::disk('public')->exists($path)) {
            Storage::disk('public')->put($path, file_get_contents($source));
        }

        return $path;
    }

