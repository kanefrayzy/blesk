<?php

namespace Database\Seeders;

use App\Enums\Rubric;
use App\Models\Post;
use Illuminate\Database\Seeder;

/**
 * Первая новость раздела. Заводится через updateOrCreate: сеялку можно
 * прогнать повторно после выкладки, дубля не будет, а правки редактора
 * в панели она не затрёт — сверяется по адресу страницы.
 */
class PostSeeder extends Seeder
{
    public function run(): void
    {
        Post::query()->firstOrCreate(
            ['slug' => 'rebrending-i-lichnyy-kabinet'],
            [
                'rubric' => Rubric::News,
                'title' => 'Новый фирменный стиль «Блеска» и личный кабинет с отслеживанием заказа',
                'excerpt' => 'Химчистка обновила фирменный стиль и запустила новый сайт. '
                    .'Следующий шаг — личный кабинет: он покажет, на каком участке '
                    .'производства находится вещь, и соберёт историю заказов.',
                'seo_description' => 'Химчистка «Блеск» в Жуковском обновила фирменный стиль '
                    .'и запустила новый сайт с личным кабинетом для отслеживания заказов.',
                'published_at' => now(),
                'body' => self::body(),
            ],
        );
    }

    private static function body(): string
    {
        return <<<'HTML'
            <p>«Блеск» работает в Жуковском не первый год, и всё это время у химчистки было
            собственное производство, свои технологи и постоянные клиенты. Не хватало одного:
            чтобы всё это было видно снаружи. Мы обновили фирменный стиль и запустили новый сайт.</p>

            <h2>Новый фирменный стиль</h2>

            <p>У «Блеска» появился полноценный бренд: знак с разомкнутым кольцом и искрой,
            фирменные цвета, единая гарнитура и правила, по которым оформляются вывеска,
            упаковка, чехлы для одежды и форма сотрудников. Смысл знака простой — кольцо
            это цикл ухода за вещью, от приёма до выдачи, а искра результат.</p>

            <p>Вместе со стилем поменялся и тон. Химчистка перестала быть «пунктом приёма»
            и говорит о себе так, как есть на самом деле: центр профессионального ухода
            за вещами с собственным цехом и итальянским оборудованием.</p>

            <h2>Новый сайт</h2>

            <p>Сайт собран заново. На нём видно, что происходит с вещью внутри производства,
            какие услуги есть и как до нас доехать. Дальше он будет расти: появятся отдельные
            страницы по изделиям, материалам и видам загрязнений, а также раздел со статьями
            об уходе за вещами дома.</p>

            <h2>Личный кабинет: что в нём будет</h2>

            <p>Самое частое, что спрашивают в приёмном пункте, — «готово ли?». Чтобы на этот
            вопрос не нужно было звонить, мы готовим личный кабинет. В нём будет:</p>

            <ul>
                <li>статус заказа — на каком участке изделие прямо сейчас;</li>
                <li>история заказов за всё время, а не только текущий;</li>
                <li>стоимость по заказу без звонка в приёмный пункт;</li>
                <li>фотографии изделия, сделанные при приёмке;</li>
                <li>рекомендации по уходу за конкретной вещью;</li>
                <li>накопленные бонусы — этот модуль появится позже остальных.</li>
            </ul>

            <p>Страница входа на сайте уже открыта. Кабинет заработает, когда его подключат
            к системе учёта заказов производства, — до этого момента мы не показываем в нём
            данных, которых там ещё нет.</p>

            <h2>Что дальше</h2>

            <p>Ближайшие планы — съёмка производства, страницы услуг под каждое изделие
            и пункты приёма в соседних городах. О каждом шаге будем писать здесь.</p>
            HTML;
    }
}
